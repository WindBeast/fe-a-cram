const fields = [];
for (const raw of src.split('\n')) {
  const line = raw.trim();
  if (!line) continue;
  let m;
  if ((m = line.match(/^#(\w+) (.+)$/))) {
    fields.push({ id: m[1], name: m[2], majors: [] });
  } else if ((m = line.match(/^## (\d+) (.+)$/))) {
    fields.at(-1).majors.push({ no: Number(m[1]), name: m[2], middles: [] });
  } else if ((m = line.match(/^(\d+) (.+?)：(.+)$/))) {
    const no = Number(m[1]);
    const minors = m[3].split('／').map((name, i) => ({
      id: `${String(no).padStart(2, '0')}-${i + 1}`,
      name,
    }));
    fields.at(-1).majors.at(-1).middles.push({ no, name: m[2], minors });
  } else {
    throw new Error(`解釈できない行: ${line}`);
  }
}

const out = {
  note: 'IPA 基本情報技術者試験 シラバス Ver.9.2（2026年1月8日掲載）の大分類・中分類・小分類。小分類 id は「中分類番号2桁-小分類の並び順」。',
  fields,
};
writeFileSync(new URL('../content/syllabus.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
const count = fields.flatMap((f) => f.majors.flatMap((ma) => ma.middles.flatMap((mi) => mi.minors))).length;
console.log(`syllabus.json を書き出しました（小分類 ${count} 件）`);
